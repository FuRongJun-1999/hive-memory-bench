# -*- coding: utf-8 -*-
import math
def binom_sf(k, n, p):
    if n == 0: return 1.0
    return min(1.0, sum(math.comb(n, i) * p**i * (1-p)**(n-i) for i in range(k, n+1)))
n = 182
print('=== 用两个基线算同一个读数 ===')
print('%-22s %6s %10s %10s' % ('场景', '对/182', 'p(基线0.2)', 'p(基线0.25)'))
for label, k in (('全选 A', 46), ('随机(作者测)', 40), ('灵枢 76.9%', 140), ('千问 84.1%', 153), ('直喂 98.9%', 180)):
    print('%-22s %6d %10.4f %10.4f' % (label, k, binom_sf(k, n, 0.2), binom_sf(k, n, 0.25)))
print()
print('=== 关键：全选 A 的 25% 是运气还是必然 ===')
print('  A 答案数: 46 / 182 = %.1f%%' % (46/182*100))
print('  E 答案数:   1 / 182 = %.2f%%' % (1/182*100))
print('  → 若系统学会「永不选 E」，随机期望就是 1/4 = 25%%')
print('  → 所以「全选 A 得 25%%」在 p=0.25 下完全正常（p=%.2f），' % binom_sf(46, n, 0.25))
print('    而非作者写的「p=0.057 接近显著」——那是用 0.2 算的。')
print()
print('=== 反推：若题库真按 5 选 1 设计，E 该有多少题是答案 ===')
print('  均匀 5 选 1 期望: %.1f 题' % (n/5))
print('  实际: 1 题  → 差 %.1f 题' % (n/5 - 1))